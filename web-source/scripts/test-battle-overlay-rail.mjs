import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHarness,installEnvironment,loadModules} from './ux-hook-harness.mjs';
import {createDemoScene} from '../lib/firefight/scene.mjs';
installEnvironment();const h=createHarness();
const {BattleApp}=await loadModules(h,undefined,{actualSharedBattle:true});
const scene=createDemoScene();let opens=0,commands=0;
const props={scene,role:'gm',onCommand:()=>{commands++;},onPreview:async()=>({ok:true}),onExit(){}};
h.mount(BattleApp,props);await h.flush();
assert(!h.button('Режим тестового обзора'));assert(h.text().includes('ГМ · вся сцена'));
await h.click('Меню боя');assert(!h.button('Режимы и настройки стенда'));h.dispose();
h.mount(BattleApp,{...props,onTestMenu:()=>opens++});await h.flush();
await h.click('Режим тестового обзора');assert.equal(opens,1);assert.equal(commands,0);
await h.click('Меню боя');await h.click('Режимы и настройки стенда');assert.equal(opens,2);
assert(!h.find(n=>n.props['aria-label']==='Управление боем'),'Opening external test settings closes the battle panel');
assert.equal(commands,0,'Changing test chrome never sends gameplay commands');h.dispose();
const css=await readFile(new URL('../components/battle/battle.css',import.meta.url),'utf8');
const rail=css.slice(css.lastIndexOf('/* Phone feedback:'));
assert.match(rail,/scene-header\.battlefield-rail\{position:absolute;[^}]*background:transparent;pointer-events:none/);
assert.match(rail,/header-controls\{pointer-events:auto;min-height:44px/);
assert.match(rail,/initiative-slot\{pointer-events:auto/);
assert.match(rail,/battle-control-menu[^}]*top:calc\(var\(--battle-overlay-height\) \+ 8px\)/);
assert.match(rail,/intent-panel\{top:calc\(var\(--battle-overlay-height\) \+ 8px\);max-height:calc\(100% - var\(--battle-overlay-height\) - 16px\)/);
assert.match(rail,/test-view-button\{[^}]*min-height:44px;min-width:44px/);
console.log('Overlay rail: no reserved strip, transparent map gaps, 44px controls, panels below rail, optional test menu without commands. Hook/CSS contract, not browser pixels.');

assert.match(rail, /@media\(orientation:portrait\) and \(max-width:700px\)/);
assert.match(rail, /battle-app\[data-has-initiative=true\]\{--battle-overlay-height:calc\(var\(--battle-rail-height\) \+ 44px\)/);
assert.match(rail, /initiative-track\{top:var\(--battle-rail-height\);left:6px;right:6px/);
assert.match(rail, /intent-panel\{left:8px;right:8px;width:calc\(100% - 16px\)/);
h.mount(BattleApp,props);await h.flush();
assert.equal(h.find(n=>n.type==='main').props['data-has-initiative'],false);
h.dispose();h.mount(BattleApp,{...props,scene:{...scene,order:['ray']}});await h.flush();
assert.equal(h.find(n=>n.type==='main').props['data-has-initiative'],true);h.dispose();
